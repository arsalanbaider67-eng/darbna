// CarPlay (navigation app). Only used when DARBNA_CARPLAY=1 (see app.config.ts): Apple must first
// grant the CarPlay Navigation entitlement to the App ID, otherwise signed builds fail.
//
// CarPlay needs UIApplicationSceneManifest, which switches the whole app to scenes. Expo's
// AppDelegate makes its window in didFinishLaunching (not tied to a scene), so we:
//  1. declare a phone scene (PhoneSceneDelegate) and a CarPlay scene (CarSceneDelegate),
//  2. PhoneSceneDelegate (Swift) moves the AppDelegate's window onto the phone scene and forwards
//     opened links / user activities to the AppDelegate (with scenes iOS no longer calls
//     application(_:open:options:) — without this, darbna:// links and "Share → Darbna" break),
//  3. CarSceneDelegate (Objective-C) hands the CarPlay interface to react-native-carplay,
//  4. adds the com.apple.developer.carplay-maps entitlement.
const fs = require("fs");
const path = require("path");
const { withInfoPlist, withEntitlementsPlist, withDangerousMod, withXcodeProject } = require("expo/config-plugins");

const PHONE_SWIFT = `import UIKit

// Generated by plugins/withCarPlay.js — the iPhone screen as a scene (needed once CarPlay is on).
@objc(PhoneSceneDelegate)
class PhoneSceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
          let delegate = UIApplication.shared.delegate,
          let optWindow = delegate.window,
          let window = optWindow
    else { return }
    window.windowScene = windowScene
    window.makeKeyAndVisible()
    self.window = window
    // Opened from a link or "Share → Darbna" while the app wasn't running.
    if let ctx = connectionOptions.urlContexts.first {
      DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) { self.forward(ctx.url) }
    }
    if let activity = connectionOptions.userActivities.first {
      DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) { self.forward(activity) }
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    if let ctx = URLContexts.first { forward(ctx.url) }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    forward(userActivity)
  }

  private func forward(_ url: URL) {
    _ = UIApplication.shared.delegate?.application?(UIApplication.shared, open: url, options: [:])
  }

  private func forward(_ activity: NSUserActivity) {
    _ = UIApplication.shared.delegate?.application?(UIApplication.shared, continue: activity, restorationHandler: { _ in })
  }
}
`;

const CAR_H = `// Generated by plugins/withCarPlay.js
#import <UIKit/UIKit.h>
#import <CarPlay/CarPlay.h>

@interface CarSceneDelegate : UIResponder <CPTemplateApplicationSceneDelegate>
@end
`;

const CAR_M = `// Generated by plugins/withCarPlay.js — gives the CarPlay screen to react-native-carplay.
#import "CarSceneDelegate.h"
#if __has_include(<react-native-carplay/RNCarPlay.h>)
#import <react-native-carplay/RNCarPlay.h>
#else
#import "RNCarPlay.h"
#endif

@implementation CarSceneDelegate

- (void)templateApplicationScene:(CPTemplateApplicationScene *)templateApplicationScene
   didConnectInterfaceController:(CPInterfaceController *)interfaceController
                        toWindow:(CPWindow *)window {
  [RNCarPlay connectWithInterfaceController:interfaceController window:window];
}

- (void)templateApplicationScene:(CPTemplateApplicationScene *)templateApplicationScene
didDisconnectInterfaceController:(CPInterfaceController *)interfaceController
                      fromWindow:(CPWindow *)window {
  [RNCarPlay disconnect];
}

- (void)sceneDidBecomeActive:(UIScene *)scene {
  [RNCarPlay stateChanged:YES];
}

- (void)sceneWillResignActive:(UIScene *)scene {
  [RNCarPlay stateChanged:NO];
}

@end
`;

function appDir(iosRoot) {
  for (const e of fs.readdirSync(iosRoot, { withFileTypes: true })) {
    if (e.isDirectory() && !e.name.startsWith(".") && e.name !== "Pods" && e.name !== "build"
      && fs.existsSync(path.join(iosRoot, e.name, "AppDelegate.swift"))) return e.name;
  }
  throw new Error("withCarPlay: AppDelegate.swift not found under ios/");
}

module.exports = function withCarPlay(config) {
  config = withInfoPlist(config, (cfg) => {
    const manifest = cfg.modResults.UIApplicationSceneManifest ?? {};
    manifest.UIApplicationSupportsMultipleScenes = false;
    manifest.UISceneConfigurations = {
      ...(manifest.UISceneConfigurations ?? {}),
      UIWindowSceneSessionRoleApplication: [{
        UISceneClassName: "UIWindowScene", UISceneConfigurationName: "Phone", UISceneDelegateClassName: "PhoneSceneDelegate",
      }],
      CPTemplateApplicationSceneSessionRoleApplication: [{
        UISceneClassName: "CPTemplateApplicationScene", UISceneConfigurationName: "CarPlay", UISceneDelegateClassName: "CarSceneDelegate",
      }],
    };
    cfg.modResults.UIApplicationSceneManifest = manifest;
    return cfg;
  });

  config = withEntitlementsPlist(config, (cfg) => {
    cfg.modResults["com.apple.developer.carplay-maps"] = true;
    return cfg;
  });

  config = withDangerousMod(config, ["ios", (cfg) => {
    const root = cfg.modRequest.platformProjectRoot;
    const dir = path.join(root, appDir(root));
    fs.writeFileSync(path.join(dir, "PhoneSceneDelegate.swift"), PHONE_SWIFT);
    fs.writeFileSync(path.join(dir, "CarSceneDelegate.h"), CAR_H);
    fs.writeFileSync(path.join(dir, "CarSceneDelegate.m"), CAR_M);
    return cfg;
  }]);

  config = withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const name = cfg.modRequest.projectName;
    const group = project.findPBXGroupKey({ name });
    if (!group) throw new Error(`withCarPlay: Xcode group "${name}" not found`);
    for (const f of ["PhoneSceneDelegate.swift", "CarSceneDelegate.m"]) {
      if (!project.hasFile(`${name}/${f}`)) project.addSourceFile(`${name}/${f}`, {}, group);
    }
    if (!project.hasFile(`${name}/CarSceneDelegate.h`)) project.addHeaderFile(`${name}/CarSceneDelegate.h`, {}, group);
    return cfg;
  });

  return config;
};
