// Web build step: turns every Material Community icon the app uses into inline SVG path data
// (src/components/iconPaths.web.ts), so icons show even where a browser blocks downloaded fonts
// (iPhone Lockdown Mode, some in-app browsers, data savers). Native apps keep the icon font.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

/** Find a file inside an installed package by walking up node_modules folders (avoids "exports" limits). */
function pkgFile(pkg, rel) {
  for (let d = root; ; d = path.dirname(d)) {
    const f = path.join(d, "node_modules", pkg, rel);
    if (fs.existsSync(f)) return f;
    if (path.dirname(d) === d) throw new Error(`not found: ${pkg}/${rel}`);
  }
}

let glyphs, mdi;
try {
  const vendor = path.dirname(pkgFile("@expo/vector-icons", "package.json"));
  const candidates = [
    "build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json",
    "build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json",
  ];
  const gm = candidates.map((c) => path.join(vendor, c)).find((f) => fs.existsSync(f));
  glyphs = JSON.parse(fs.readFileSync(gm ?? pkgFile("@expo/vector-icons", candidates[0]), "utf8"));
  mdi = require(path.dirname(pkgFile("@mdi/js", "package.json")) + "/mdi.js");
} catch (e) {
  // Never block a release over this: the app falls back to the icon font.
  console.log(`::warning title=web icons::SVG icons skipped (${e.message}); using the icon font`);
  process.exit(0);
}

const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f.name) && !f.name.startsWith("iconPaths")) files.push(p);
  }
})(path.join(root, "src"));
files.push(path.join(root, "App.tsx"));

const used = new Set();
for (const f of files) {
  for (const m of fs.readFileSync(f, "utf8").matchAll(/["']([a-z0-9]+(?:-[a-z0-9]+)*)["']/g)) if (m[1] in glyphs) used.add(m[1]);
}
const out = {};
const missing = [];
for (const name of [...used].sort()) {
  const key = "mdi" + name.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
  if (mdi[key]) out[name] = mdi[key];
  else missing.push(name);
}
fs.writeFileSync(
  path.join(root, "src/components/iconPaths.web.ts"),
  "// GENERATED by scripts/gen-web-icons.mjs during the web build — do not edit.\n" +
    `export const ICON_PATHS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`,
);
console.log(`web icons: ${Object.keys(out).length} as SVG` + (missing.length ? `; font fallback for: ${missing.join(", ")}` : ""));
